function checkCode(descriptor: string): string {
  const h = Buffer.from(sha256B64url(descriptor), 'base64url').toString('hex').toUpperCase();
  return `${h.slice(0, 4)}-${h.slice(4, 8)}-${h.slice(8, 12)}`;
}


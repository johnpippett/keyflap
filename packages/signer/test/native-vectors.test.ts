function generic(): unknown[] {
  return [
    { b: 1, a: [true, false, null, -5, 0, 9007199254740991], é: 'x', '😀': 'emoji', '￿': 'last' },
    { nested: { z: { y: [] }, a: {} }, '': 'empty key', A: 'upper', a: 'lower' },
  ];
}

function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  const o = value as Record<string, unknown>;
  return `{${Object.keys(o)
    .sort()
    .map((k) => `${JSON.stringify(k)}:${canonicalJson(o[k])}`)
    .join(',')}}`;
}

function build() {
  const key = createPrivateKey({ key: TEST_KEY, format: 'jwk' });
  const keyId = nativeKeyId(TEST_KEY.x, TEST_KEY.y);
  const descriptor = nativeApproverDescriptor({
    keyId,
    x: TEST_KEY.x,
    y: TEST_KEY.y,
    origin: ORIGIN,
    userVerification: 'biometry',
  });
  const passkey = {
    credentialId: 'cred-AbC_123',
    x: TEST_KEY.x,
    y: TEST_KEY.y,
    rpId: 'broker.tail1234.ts.net',
    origin: ORIGIN,
  };
  return {
    key,
    deterministic: {
      comment:
        'Generated by packages/signer/test/native-vectors.test.ts (UPDATE_VECTORS=1). Test-only key.',
      statements: statements().map(({ name, statement }) => {
        const bytes = nativeApprovalSigningBytes(statement);
        return {
          name,
          statement,
          nativeSigningBytes: bytes.toString('base64'),
          nativeSigningSha256: sha256B64url(bytes),
          ed25519SigningBytes: approvalSigningBytes(statement).toString('base64'),
        };
      }),
      generic: generic().map((value) => ({ value, canonical: canonicalJson(value) })),
      fillScopes: (['password', 'totp', 'password+totp'] as const).map((t) => {
        const fields = t === 'password+totp' ? (['password', 'totp'] as const) : ([t] as const);
        const scope = fillScope([...fields]);
        return { credentialType: t, scope, hash: sha256B64url(scope) };
      }),
      native: {
        privateKeyJwk: TEST_KEY,
        x: TEST_KEY.x,
        y: TEST_KEY.y,
        keyId,
        origin: ORIGIN,
        descriptor,
        descriptorSha256: sha256B64url(descriptor),
        checkCode: checkCode(descriptor),
        pairingProofBytes: nativePairingProofBytes(descriptor).toString('base64'),
      },
      passkeyDescriptor: {
        ...passkey,
        descriptor: approverDescriptor(passkey),
        checkCode: checkCode(approverDescriptor(passkey)),
      },
    },
  };
}

describe('native approver cross-language vectors', () => {
  it('ts-vectors.json matches the TypeScript encoders, and its signatures verify', () => {
    const { key, deterministic } = build();
    if (process.env.UPDATE_VECTORS === '1' || !existsSync(TS_FILE)) {
      const s0 = deterministic.statements[0]?.statement as ApprovalStatement;
      const file = {
        ...deterministic,
        signatures: {
          statementIndex: 0,
          statementDer: sign('sha256', nativeApprovalSigningBytes(s0), {
            key,
            dsaEncoding: 'der',
          }).toString('base64url'),
          proofDer: sign('sha256', nativePairingProofBytes(deterministic.native.descriptor), {
            key,
            dsaEncoding: 'der',
          }).toString('base64url'),
        },
      };
      writeFileSync(TS_FILE, `${JSON.stringify(file, null, 2)}\n`);
    }
    const file = JSON.parse(readFileSync(TS_FILE, 'utf8'));
    const { signatures, ...rest } = file;
    expect(rest).toEqual(deterministic);
    const s0 = deterministic.statements[0]?.statement as ApprovalStatement;
    const pub = { x: TEST_KEY.x, y: TEST_KEY.y };
    expect(
      verifyNativeSignature(pub, nativeApprovalSigningBytes(s0), signatures.statementDer),
    ).toBe(true);
    expect(
      verifyNativeSignature(
        pub,
        nativePairingProofBytes(deterministic.native.descriptor),
        signatures.proofDer,
      ),
    ).toBe(true);
  });

  it('a key, pairing proof and approval signed by the Swift core are accepted by the signer', () => {
    expect(
      existsSync(SWIFT_FILE),
      'run the Swift tests with WRITE_VECTORS=1 (docs/integrations/ios-app.md)',
    ).toBe(true);
    const v = JSON.parse(readFileSync(SWIFT_FILE, 'utf8'));
    expect(nativeKeyId(v.x, v.y)).toBe(v.keyId);
    const descriptor = nativeApproverDescriptor({
      keyId: v.keyId,
      x: v.x,
      y: v.y,
      origin: v.origin,
      userVerification: 'biometry',
    });
    expect(v.descriptor).toBe(descriptor);
    expect(v.checkCode).toBe(checkCode(descriptor));
    expect(Buffer.from(v.nativeSigningBytes, 'base64')).toEqual(
      nativeApprovalSigningBytes(v.statement),
    );

    const handler = new SignerHandler({
      store: KeyStore.open(join(tmpDir(), 'keys'), 'pw'),
      trustedApproverKeys: {},
    });
    expect(
      handler.handle({
        op: 'add_native_approver',
        key: { x: v.x, y: v.y, origin: v.origin, userVerification: 'biometry' },
        proof: v.proof,
      }),
    ).toEqual({ ok: true, result: { added: true, keyId: v.keyId } });
    const approval: NativeApproval = {
      statement: v.statement,
      approverKeyId: v.keyId,
      native: { signature: v.signature },
    };
    const key = {
      keyId: v.keyId,
      x: v.x,
      y: v.y,
      origin: v.origin,
      userVerification: 'biometry' as const,
      createdAt: 0,
    };
    expect(verifyNativeApproval(approval, key)).toEqual({ ok: true });
    expect(
      verifyNativeApproval(
        { ...approval, statement: { ...v.statement, requestId: randomUUID() } },
        key,
      ),
    ).toEqual({ ok: false, reason: 'bad_signature' });
  });
});

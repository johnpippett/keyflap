const LABEL = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;

export function normalizeRiskDomain(d: unknown): string | null {
  if (typeof d !== 'string') return null;
  const s = d.trim().toLowerCase().replace(/\.$/, '');
  if (s.length === 0 || s.length > 253) return null;
  return s.split('.').every((l) => LABEL.test(l)) ? s : null;
}

export function isHighRisk(host: string, extra: readonly string[] = []): boolean {
  if (typeof host !== 'string' || host.length === 0) return true;
  const h = host.toLowerCase().replace(/\.$/, '');
  if (h !== 'localhost' && registrableDomain(h) === null) return true;
  for (const list of [BUILTIN_HIGH_RISK, extra]) {
    for (const d of list) if (h === d || h.endsWith(`.${d}`)) return true;
  }
  return false;
}

export function isHighRiskOrigin(origin: string, extra: readonly string[] = []): boolean {
  try {
    return isHighRisk(new URL(origin).hostname, extra);
  } catch {
    return true;
  }
}

